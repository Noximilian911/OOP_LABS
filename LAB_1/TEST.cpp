// ==========================================
unsigned n = 5;
int* p = new int[n]{1, 2, 3, 4, 5};

// По индексам:
for (unsigned i = 0; i < n; i++)
    cout << p[i] << " ";

// Через разыменование со смещением:
for (unsigned i = 0; i < n; i++)
    cout << *(p + i) << " ";

// Вспомогательным указателем:
for (int* q = p; q != p + n; q++)
    cout << *q << " ";

delete[] p;
p = nullptr;


// ==========================================
//    ПРАВИЛА РАБОТЫ С NEW / DELETE
// ==========================================
// 1) new — парный delete. new[] — парный delete[].
// 2) После delete сразу обнуляй: p = nullptr;
// 3) Перед разыменованием проверяй: if (p != nullptr)
// 4) Не имей двух «хозяев» одной памяти.
// 5) Можешь обойтись vector — обойдись.


// ==========================================
//    МИНИ-ШАБЛОН ДЛЯ ЗАДАЧИ
// ==========================================
int main() {
    int N;
    cout << "N = ";
    cin >> N;

    int* arr = new int[N]{};          // выделили и занулили

    for (int i = 0; i < N; i++) {     // заполнили
        arr[i] = i * 10;
    }

    for (int i = 0; i < N; i++) {     // использовали
        cout << arr[i] << " ";
    }
    cout << endl;

    delete[] arr;                     // освободили
    arr = nullptr;                    // обнулили

    if (arr == nullptr) {
        cout << "Память освобождена" << endl;
    }
}