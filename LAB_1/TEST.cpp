// ==========================================
//    УТЕЧКА ПАМЯТИ
// ==========================================
// new есть, delete нет → память остаётся занятой до конца программы.

void leak() {
    int* p = new int[1000];
    // забыли delete[] p;  ← утечка
}


// ==========================================
//    DANGLING POINTER
// ==========================================
// Указатель на освобождённую память.

int* dp = new int{42};
delete dp;
cout << *dp << endl;   // UB — 42, мусор, краш, как повезёт

// Компилятор обычно не предупреждает. Самое коварное место в C++.


// ==========================================
//    ОБНУЛЕНИЕ УКАЗАТЕЛЯ
// ==========================================
// После delete[] указатель всё ещё хранит старый адрес.
// Это опасно. Правило: удалил — обнули.

int* sp = new int[5];
delete[] sp;
sp = nullptr;

// Теперь *sp = 5 крашнется сразу и заметно,
// а delete[] sp безопасно (delete к nullptr — no-op).

// Проверка перед использованием:
if (sp != nullptr) {
    cout << sp[0];
}


