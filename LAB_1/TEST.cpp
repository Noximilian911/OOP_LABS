// ==========================================
//    DELETE vs DELETE[]
// ==========================================
// Одиночный объект — delete:
int* p = new int;
delete p;

// Массив — delete[] с квадратными скобками:
int* arr = new int[10];
delete[] arr;

// Перепутал — UB. Может крашнуть, может молча испортить память.


// ==========================================
//    СТАТИЧЕСКИЙ / ДИНАМИЧЕСКИЙ / VECTOR
// ==========================================
// Статический: размер фиксирован на этапе компиляции
int a[10];

// Динамический: размер задаётся во время работы, надо руками delete[]
int* b = new int[10];

// vector: гибкий размер, память освобождается сам
vector<int> c(10);

// В реальном коде — всегда vector. new[] только там, где требует препод.


// ==========================================
//    ИНИЦИАЛИЗАЦИЯ ПРИ NEW
// ==========================================
